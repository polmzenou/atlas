def step(label, method, target, token=None, body=None, status=200, code=None, field=None, headers=None,
         example=None, checks=(), raw_body=None, content_type="application/json"):
    return {"label": label, "method": method, "target": target, "token": token, "body": body, "raw_body": raw_body,
            "status": status, "code": code, "field": field, "headers": headers or {}, "example": example,
            "checks": list(checks), "content_type": content_type}


def ids(r):
    return [i["id"] for i in r.body["items"]]


def events(m, iid):
    return [(e["revision"], e["type"]) for e in m.events.get(iid, [])]


